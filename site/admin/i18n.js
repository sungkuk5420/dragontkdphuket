const read = () => { try { return localStorage.getItem(KEY); } catch { return null; } };
let cur = D[read()] ? read() : 'ko';

export const lang = () => cur;

/** 키 → 현재 언어 문구. 빠진 번역은 한국어로, 그것도 없으면 키를 그대로 보여 준다(누락이 화면에 드러나게). */
export function t(key, vars = {}, as = cur) {
  const s = D[as][key] ?? D.ko[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
}

/** 정적 HTML: data-i18n → 글자, data-i18n-html → HTML, data-i18n-aria → aria-label */
export function applyStatic(root = document) {
  document.documentElement.lang = cur;
  document.title = t('doc.title');
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  root.querySelectorAll('[data-lang-pick]').forEach((el) => { el.setAttribute('aria-pressed', String(el.dataset.langPick === cur)); });
}

// 언어 버튼(data-lang-pick)은 index.html 의 상단바·로그인 카드에 있다
const listeners = [];
export const onLangChange = (fn) => listeners.push(fn);
export function setLang(next) {
  if (!D[next] || next === cur) return;
  cur = next;
  try { localStorage.setItem(KEY, next); } catch { /* 저장소 차단 — 이번 탭에서만 바뀐다 */ }
  applyStatic();
  listeners.forEach((fn) => fn());
}
document.addEventListener('click', (e) => {
  const b = e.target.closest('[data-lang-pick]');
  if (b) setLang(b.dataset.langPick);
});
